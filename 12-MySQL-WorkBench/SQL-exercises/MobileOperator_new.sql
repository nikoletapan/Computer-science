-- CREATE DATABASE MobileOperator;
USE MobileOperator;

CREATE TABLE Towns (
  ID INT PRIMARY KEY AUTO_INCREMENT,
  Name VARCHAR(30)
);

CREATE TABLE Employees (
    ID INT PRIMARY KEY AUTO_INCREMENT,
    FirstName VARCHAR(50),
    MiddleName VARCHAR(50),
    LastName VARCHAR(50),
    EGN CHAR(10),
    JobTitle VARCHAR(50),
    Salary DECIMAL(10, 2),
    HireDate DATE,
    ManagerID INT,
	TownID INT,
    FOREIGN KEY (ManagerID) REFERENCES Employees(ID),
	FOREIGN KEY (TownID) REFERENCES Towns(ID)
);

CREATE TABLE SubscriptionPlans (
  ID INT PRIMARY KEY AUTO_INCREMENT,
  Name VARCHAR(50),
  Price DECIMAL(10,2),
  IncludedMinutes INT,
  IncludedMessages INT,
  IncludedData INT
);

CREATE TABLE Customers (
  ID INT PRIMARY KEY AUTO_INCREMENT,
  FirstName VARCHAR(50),
  LastName VARCHAR(50),
  SubscriptionPlanID INT,
  ContactNumber VARCHAR(15),
  TownID INT,
  Address VARCHAR(100),
  FOREIGN KEY (SubscriptionPlanID) REFERENCES SubscriptionPlans(ID),
  FOREIGN KEY (TownID) REFERENCES Towns(ID)
);

CREATE TABLE Contracts (
  ID INT PRIMARY KEY AUTO_INCREMENT,
  Number CHAR(6),
  StartingDate DATE,
  Duration INT,
  CustomerID INT UNIQUE,
  FOREIGN KEY (CustomerID) REFERENCES Customers(ID)
);

CREATE TABLE AdditionalPackages (
  ID INT PRIMARY KEY AUTO_INCREMENT,
  Name VARCHAR(50),
  Description VARCHAR(200),
  Price DECIMAL(10,2)
);

CREATE TABLE CustomersAdditionalPackages(
  CustomerID int NOT NULL,
  PackageID int NOT NULL,
  FOREIGN KEY (CustomerID) REFERENCES Customers(ID),
  FOREIGN KEY (PackageID) REFERENCES AdditionalPackages(ID),
  CONSTRAINT PK_CustomerAdditionalPackages PRIMARY KEY (CustomerID, PackageID)
);

